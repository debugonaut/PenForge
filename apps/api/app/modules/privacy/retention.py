"""Conservative versioned retention, dry-run first; unknown objects are never deleted."""

import asyncio
import hashlib
import json
from datetime import timedelta
from uuid import UUID

import sqlalchemy as sa
from penforge_contracts import canonical_bytes

from app.db import models as m
from app.modules.privacy.repository import PrivacyRepository
from app.modules.privacy.schemas import RetentionPolicy


def identifiers(value):
    if isinstance(value, dict):
        return set().union(*(identifiers(v) for v in value.values()), set())
    if isinstance(value, list):
        return set().union(*(identifiers(v) for v in value), set())
    if isinstance(value, str):
        try:
            return {UUID(value)}
        except ValueError:
            pass
    return set()


class Retention:
    def __init__(self, privacy):
        self.privacy = privacy
        self.engine, self.storage = privacy.engine, privacy.storage

    async def inventory(self, con):
        raw = await con.scalar(
            sa.select(m.system_settings.c.value).where(
                m.system_settings.c.key == "retention_policy.v1"
            )
        )
        policy = RetentionPolicy.model_validate(raw or {})
        now = await PrivacyRepository(con).now()
        refs: set[UUID] = set()
        for table, columns in (
            (m.samples, ["asset_id"]),
            (m.glyph_revisions, ["outline_asset_id"]),
            (m.glyph_candidates, ["outline_asset_id", "evidence"]),
            (m.font_exports, ["asset_id", "validation_report_asset_id"]),
            (m.ml_result_artifacts, ["manifest_asset_id"]),
            (m.style_profiles, ["embedding_asset_id", "metrics"]),
        ):
            for row in (await con.execute(sa.select(*[table.c[c] for c in columns]))).mappings():
                for value in row.values():
                    refs |= {value} if isinstance(value, UUID) else identifiers(value)
        jobs = {j["id"]: j for j in (await con.execute(sa.select(m.jobs))).mappings()}
        checkpoints = list((await con.execute(sa.select(m.job_checkpoints))).mappings())
        expired_checkpoints = {
            c["id"]
            for c in checkpoints
            if jobs.get(c["job_id"], {}).get("state") in {"succeeded", "failed", "canceled"}
            and jobs[c["job_id"]]["finished_at"]
            and jobs[c["job_id"]]["finished_at"]
            < now - timedelta(seconds=policy.checkpoint_seconds)
        }
        for checkpoint in checkpoints:
            if checkpoint["id"] not in expired_checkpoints:
                refs.add(checkpoint["manifest_asset_id"])
        assets = list((await con.execute(sa.select(m.assets))).mappings())
        # Referenced immutable manifests may refer to child crop/mask/checkpoint IDs.
        # Read only JSON known to be generated by a bounded worker, never arbitrary uploads.
        for asset in assets:
            if (
                asset["id"] in refs
                and asset["mime_type"] == "application/json"
                and asset["kind"] in {"checkpoint", "validation_report"}
            ):
                try:
                    data = await asyncio.to_thread(
                        self.storage.read_object, asset["storage_key"], max_bytes=32 * 1024 * 1024
                    )
                    refs |= identifiers(json.loads(data))
                except Exception:
                    # Unreadable references cause retention to preserve all scope assets.
                    refs |= {a["id"] for a in assets if a["project_id"] == asset["project_id"]}
        eligible = []
        for asset in assets:
            if asset["id"] in refs or asset["state"] == "deleted":
                continue
            job = jobs.get(asset["worker_job_id"] or asset["verify_job_id"])
            if job and job["state"] not in {"succeeded", "failed", "canceled"}:
                continue
            if (
                asset["kind"]
                in {
                    "original_upload",
                    "raw_strokes",
                    "vector",
                    "export",
                    "validation_report",
                    "style_embedding",
                }
                and asset["state"] == "ready"
            ):
                continue
            threshold = (
                policy.checkpoint_seconds
                if asset["kind"] == "checkpoint"
                else policy.derived_seconds
            )
            timestamp = (
                max(asset["last_used_at"], job["finished_at"])
                if job and job["finished_at"]
                else asset["last_used_at"]
            )
            stale_pending = (
                asset["state"] == "pending_upload"
                and asset["expires_at"]
                and asset["expires_at"] < now
            )
            if stale_pending:
                age = (
                    policy.pending_upload_seconds
                    if asset["kind"] == "original_upload"
                    else policy.staged_seconds
                )
                stale_pending = asset["created_at"] < now - timedelta(seconds=age)
            if (
                stale_pending
                or asset["state"] in {"expired", "rejected"}
                or asset["state"] == "ready"
                and timestamp < now - timedelta(seconds=threshold)
            ):
                # Keep parent rows when another asset's immutable parent lineage needs it.
                if any(a["parent_asset_id"] == asset["id"] for a in assets):
                    continue
                eligible.append(asset["id"])
        body = dict(
            version=1,
            policy=policy.model_dump(),
            asset_ids=sorted(str(a) for a in eligible),
            checkpoint_ids=sorted(str(c) for c in expired_checkpoints),
            referenced_assets_preserved=len(refs),
            observed_at=now.isoformat(),
            dry_run=True,
        )
        body["report_hash"] = hashlib.sha256(canonical_bytes(body)).hexdigest()
        return body

    async def report(self):
        async with self.engine.begin() as con:
            return await self.inventory(con)

    async def apply(self, report):
        body = {k: v for k, v in report.items() if k != "report_hash"}
        if report.get("report_hash") != hashlib.sha256(
            canonical_bytes(body)
        ).hexdigest() or not body.get("dry_run"):
            raise ValueError("retention_report_invalid")
        async with self.engine.begin() as con:
            await con.execute(sa.select(sa.func.pg_advisory_xact_lock(70707001)))
            # Same user/project lock order as publication; re-evaluate references live.
            await con.execute(sa.select(m.users).order_by(m.users.c.id).with_for_update())
            await con.execute(sa.select(m.projects).order_by(m.projects.c.id).with_for_update())
            current = await self.inventory(con)
            if current["policy"] != report["policy"]:
                raise ValueError("retention_policy_changed")
            asset_ids = set(report["asset_ids"]) & set(current["asset_ids"])
            cp_ids = set(report["checkpoint_ids"]) & set(current["checkpoint_ids"])
            await con.execute(
                m.job_checkpoints.delete().where(
                    m.job_checkpoints.c.id.in_([UUID(c) for c in cp_ids])
                )
            )
            assets = list(
                (
                    await con.execute(
                        sa.select(m.assets)
                        .where(m.assets.c.id.in_([UUID(a) for a in asset_ids]))
                        .with_for_update()
                    )
                ).mappings()
            )
            for asset in assets:
                await self.privacy._delete_object(asset["storage_key"])
                if asset["state"] not in {"deleting", "deleted"}:
                    await con.execute(
                        m.assets.update()
                        .where(m.assets.c.id == asset["id"])
                        .values(state="deleting")
                    )
                if asset["state"] != "deleted":
                    await con.execute(
                        m.assets.update()
                        .where(m.assets.c.id == asset["id"])
                        .values(
                            state="deleted", cleanup_completed_at=await PrivacyRepository(con).now()
                        )
                    )
                # Keep metadata lineage; release physical storage charges once.
                marker = asset["cleanup_completed_at"]
                if marker is None:
                    await self.privacy.uploads.settle_artifact_in_transaction(
                        con, asset["owner_user_id"], asset["id"], None
                    )
                    reservations = list(
                        (
                            await con.execute(
                                sa.select(m.quota_reservations).where(
                                    m.quota_reservations.c.asset_id == asset["id"],
                                    m.quota_reservations.c.status == "committed",
                                )
                            )
                        ).mappings()
                    )
                    for reservation in reservations:
                        await con.execute(
                            m.quota_balances.update()
                            .where(m.quota_balances.c.id == reservation["balance_id"])
                            .values(
                                committed=sa.func.greatest(
                                    0,
                                    m.quota_balances.c.committed
                                    - (reservation["committed_amount"] or 0),
                                )
                            )
                        )
                    await con.execute(
                        m.quota_reservations.delete().where(
                            m.quota_reservations.c.asset_id == asset["id"]
                        )
                    )
            policy = RetentionPolicy.model_validate(report["policy"])
            now = await PrivacyRepository(con).now()
            await con.execute(
                m.idempotency_keys.delete().where(
                    m.idempotency_keys.c.expires_at <= now,
                    m.idempotency_keys.c.created_at
                    < now - timedelta(seconds=policy.idempotency_seconds),
                )
            )
            await con.execute(
                m.job_events.delete().where(
                    m.job_events.c.created_at < now - timedelta(seconds=policy.event_seconds),
                    m.job_events.c.job_id.in_(
                        sa.select(m.jobs.c.id).where(
                            m.jobs.c.state.in_(["succeeded", "failed", "canceled"])
                        )
                    ),
                )
            )
            await con.execute(m.job_streams.delete().where(m.job_streams.c.expires_at < now))
            audit_removed = await con.scalar(sa.select(sa.func.penforge_prune_audit()))
            # Append-only audit is preserved conservatively; an operator can use the
            # versioned expiry inventory without bypassing the append-only guard.
            return {
                "objects_removed": len(assets),
                "audit_events_removed": audit_removed,
                "checkpoint_references_removed": len(cp_ids),
                "dry_run": False,
            }
